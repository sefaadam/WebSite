document.addEventListener('DOMContentLoaded', () => {

    /* --- Language Translation Logic --- */
    const langBtn = document.getElementById('lang-toggle');
    // Default language is 'tr'. Check if user has a saved preference, otherwise default to 'tr'
    let currentLang = localStorage.getItem('portfolio_lang') || 'tr';

    const updateLanguage = (lang) => {
        // Update document language attribute
        document.documentElement.lang = lang;
        
        // Update all data-i18n elements
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });

        // Update all data-i18n-placeholder elements (for inputs/textareas)
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[lang] && translations[lang][key]) {
                el.placeholder = translations[lang][key];
            }
        });

        // Update button text to reflect the *other* language they can switch to
        langBtn.textContent = lang === 'tr' ? 'EN' : 'TR';
        
        // Save preference
        localStorage.setItem('portfolio_lang', lang);
        currentLang = lang;
    };

    // Initialize with current language
    updateLanguage(currentLang);

    // Toggle event listener
    langBtn.addEventListener('click', () => {
        const newLang = currentLang === 'tr' ? 'en' : 'tr';
        updateLanguage(newLang);
    });

    /* --- Original Interactions --- */
    
    // 1. Scroll Reveal Animation using IntersectionObserver
    const revealElements = document.querySelectorAll('.reveal');
    const revealObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('active');
            }
        });
    }, {
        root: null,
        threshold: 0.15,
        rootMargin: "0px 0px -50px 0px"
    });

    revealElements.forEach(el => {
        revealObserver.observe(el);
    });

    // 2. Modal Logic for Projects
    const modals = document.querySelectorAll('.modal-overlay');
    const openModalBtns = document.querySelectorAll('.open-modal');
    const closeModalBtns = document.querySelectorAll('.modal-close');

    openModalBtns.forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const modalId = btn.getAttribute('data-modal');
            const targetModal = document.getElementById(modalId);
            if (targetModal) {
                targetModal.classList.add('active');
                document.body.style.overflow = 'hidden';
            }
        });
    });

    closeModalBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            modals.forEach(m => m.classList.remove('active'));
            document.body.style.overflow = 'auto';
        });
    });

    modals.forEach(modal => {
        modal.addEventListener('click', (e) => {
            if (e.target === modal) {
                modal.classList.remove('active');
                document.body.style.overflow = 'auto';
            }
        });
    });

    // 3. Navbar scroll effect
    const nav = document.querySelector('nav');
    window.addEventListener('scroll', () => {
        if (window.scrollY > 50) {
            nav.style.background = 'rgba(10, 10, 12, 0.95)';
            nav.style.boxShadow = '0 4px 30px rgba(0, 0, 0, 0.5)';
        } else {
            nav.style.background = 'rgba(10, 10, 12, 0.8)';
            nav.style.boxShadow = 'none';
        }
    });

    // 4. Email Button Expand Logic
    const emailToggle = document.getElementById('email-toggle');
    if (emailToggle) {
        emailToggle.addEventListener('click', function(e) {
            e.preventDefault(); // Prevent jump to top
            this.classList.toggle('expanded');
            e.stopPropagation(); // Prevent document click from firing immediately
        });

        // Close when clicking anywhere else
        document.addEventListener('click', function(e) {
            if (!emailToggle.contains(e.target)) {
                emailToggle.classList.remove('expanded');
            }
        });
    }
    // 5. Lightbox Logic
    const lightbox = document.getElementById('lightbox');
    const lightboxImg = document.getElementById('lightbox-img');
    const lightboxClose = document.querySelector('.lightbox-close');
    
    // Function to attach lightbox listeners to images
    const attachLightbox = () => {
        const clickableImages = document.querySelectorAll('.project-image, .modal-image, .has-image img');
        clickableImages.forEach(img => {
            img.addEventListener('click', (e) => {
                e.stopPropagation(); // Prevent triggering modal clicks
                lightboxImg.src = img.src;
                lightbox.classList.add('active');
                document.body.style.overflow = 'hidden';
            });
        });
    };

    attachLightbox();

    lightboxClose.addEventListener('click', () => {
        lightbox.classList.remove('active');
        if (!document.querySelector('.modal-overlay.active')) {
            document.body.style.overflow = 'auto';
        }
    });

    lightbox.addEventListener('click', (e) => {
        if (e.target === lightbox) {
            lightbox.classList.remove('active');
            if (!document.querySelector('.modal-overlay.active')) {
                document.body.style.overflow = 'auto';
            }
        }
    });
    // 6. Uzakdağ Demo Alert
    const uzakdagDemo = document.getElementById('uzakdag-demo');
    if (uzakdagDemo) {
        uzakdagDemo.addEventListener('click', (e) => {
            e.preventDefault();
            alert('Sitemiz çok yakında sizlerle!');
        });
    }
    // 7. EmailJS Integration
    // Not: Bu kısmın çalışması için emailjs.com üzerinden ücretsiz hesap açıp ID'leri almanız gerekir.
    (function() {
        emailjs.init("dkSnpHsM7S8-4AxSV");
    })();

    const contactForm = document.getElementById('contact-form');
    if (contactForm) {
        contactForm.addEventListener('submit', function(event) {
            event.preventDefault();
            
            // Eğer ID'ler girilmemişse uyarı ver (Kullanıcı için rehber)
            // if (this.querySelector('button').textContent === 'Mesaj Gönder') {
            //     alert('Lütfen script.js içindeki EmailJS ID\'lerini (Public Key, Service ID, Template ID) doldurun.');
            //     return;
            // }

            const btn = contactForm.querySelector('button');
            const originalText = btn.innerHTML;
            btn.innerHTML = 'Gönderiliyor...';
            btn.disabled = true;

            // SERVICE_ID ve TEMPLATE_ID alanlarını EmailJS'den alıp buraya yazmalısınız
            emailjs.sendForm('service_t3x85jm', 'template_67c8xew', this)
                .then(() => {
                    btn.innerHTML = 'Başarıyla Gönderildi!';
                    contactForm.reset();
                    setTimeout(() => {
                        btn.innerHTML = originalText;
                        btn.disabled = false;
                    }, 3000);
                }, (error) => {
                    console.error('EmailJS Hatası Detaylı:', error);
                    alert('Mesaj gönderilemedi. Hata: ' + (error.text || JSON.stringify(error)));
                    btn.innerHTML = 'Hata!';
                    btn.disabled = false;
                });
        });
    }
});
